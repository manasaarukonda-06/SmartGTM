
import streamlit as st
import pandas as pd
import plotly.express as px

# Configure the dashboard page
st.set_page_config(
    page_title="SmartGTM Dashboard",
    page_icon="📊",
    layout="wide"
)

# Display the dashboard title
st.title("SmartGTM - Go-To-Market Strategy Assistant")
st.write("Analyze business performance and explore your market.")

# Create sample business data
data = {
    "Channel": ["Social Media", "Email", "Search Ads", "Social Media", "Email", "Search Ads"],
    "Leads": [120, 90, 150, 140, 110, 180],
    "Conversions": [18, 20, 30, 25, 24, 36],
    "Marketing Spend": [6000, 3000, 8000, 6500, 3500, 9000]
}

df = pd.DataFrame(data)

# Calculate key business metrics
total_leads = df["Leads"].sum()
total_conversions = df["Conversions"].sum()
total_spend = df["Marketing Spend"].sum()

conversion_rate = (total_conversions / total_leads) * 100
cost_per_lead = total_spend / total_leads

# Display key metrics
st.subheader("Business Performance Overview")

col1, col2, col3, col4 = st.columns(4)

col1.metric("Total Leads", f"{total_leads:,}")
col2.metric("Conversions", f"{total_conversions:,}")
col3.metric("Conversion Rate", f"{conversion_rate:.2f}%")
col4.metric("Cost per Lead", f"₹{cost_per_lead:.2f}")

# Display the marketing data
st.subheader("Marketing Campaign Data")
st.dataframe(df, use_container_width=True)

# Create a chart showing leads by channel
st.subheader("Leads by Marketing Channel")

leads_by_channel = df.groupby("Channel", as_index=False)["Leads"].sum()

fig = px.bar(
    leads_by_channel,
    x="Channel",
    y="Leads",
    color="Channel",
    title="Total Leads Generated by Channel"
)

st.plotly_chart(fig, use_container_width=True)

# Create a chart comparing marketing spend and conversions
st.subheader("Marketing Spend vs Conversions")

fig2 = px.scatter(
    df,
    x="Marketing Spend",
    y="Conversions",
    color="Channel",
    size="Leads",
    hover_data=["Channel", "Leads"],
    title="Campaign Spend and Conversions"
)

st.plotly_chart(fig2, use_container_width=True)

# Display a simple recommendation
best_channel = leads_by_channel.loc[
    leads_by_channel["Leads"].idxmax(), "Channel"
]

st.subheader("Initial Marketing Insight")
st.info(
    f"{best_channel} generated the highest total number of leads "
    "in this sample dataset. Further analysis of costs and conversions "
    "is needed before deciding which channel performs best overall."
)
